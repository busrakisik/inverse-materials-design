"""BHS report artifacts with a strict boundary between plans and measurements.

The current 20-system study is a NOT_RUN protocol. No measured benchmark
results, scientific performance tables, or speedups can be created by this
module. Re-enable performance reporting only after an auditable experiment
runner and raw per-run evidence are implemented.
"""

import json
from pathlib import Path


class PaperArtifactGenerator:
    """Safe export of *planned* benchmarks, not empirical performance."""

    @staticmethod
    def generate_latex_table(json_path, out_tex_path="runs/table1_benchmark.tex"):
        """Previously produced misleading 'paper-ready' performance tables."""
        raise NotImplementedError(
            "Empirical benchmark LaTeX reporting is disabled until actual "
            "experiment runs, raw measurements, and provenance are available. "
            "For an explicitly unexecuted plan, use "
            "generate_protocol_latex_table() instead."
        )

    @staticmethod
    def generate_protocol_latex_table(
        protocol_json_path, out_tex_path="runs/benchmark_20_protocol.tex"
    ):
        """Render only an explicitly NOT_RUN benchmark protocol as a LaTeX table.

        The manifest must be generated by
        AblationBenchmarkSuite.save_protocol_manifest(). It never contains
        empirical performance metrics and is NOT a scientific results table.
        """
        source_path = Path(protocol_json_path)
        with source_path.open("r", encoding="utf-8") as handle:
            document = json.load(handle)

        if (
            not isinstance(document, dict)
            or document.get("artifact_type") != "BENCHMARK_PROTOCOL"
            or document.get("status") != "NOT_RUN"
        ):
            raise ValueError("Expected an explicitly NOT_RUN BENCHMARK_PROTOCOL.")

        systems = document.get("systems")
        if not isinstance(systems, list) or len(systems) != 20:
            raise ValueError("Expected exactly 20 protocol systems.")

        for entry in systems:
            if (
                not isinstance(entry, dict)
                or entry.get("status") != "NOT_RUN"
                or entry.get("metrics") is not None
                or entry.get("evidence_files") != []
                or not isinstance(entry.get("system"), str)
                or not isinstance(entry.get("class"), str)
            ):
                raise ValueError(
                    "Protocol must contain only NOT_RUN records without metrics."
                )

        def latex_escape(value):
            # Escape only the metacharacters appearing in table labels.
            substitutions = {
                "\\": r"\textbackslash{}",
                "&": r"\&",
                "%": r"\%",
                "$": r"\$",
                "#": r"\#",
                "_": r"\_",
                "{": r"\{",
                "}": r"\}",
            }
            return "".join(substitutions.get(character, character) for character in value)

        lines = [
            r"% STUDY PROTOCOL ONLY: NOT EXPERIMENTAL RESULTS",
            r"\begin{table}[ht]",
            r"\centering",
            r"\caption{Planned 20-system study (NOT RUN; no benchmark results).}",
            r"\label{tab:bhs_20_protocol_not_run}",
            r"\begin{tabular}{lll}",
            r"\hline",
            r"System & Material class & Status \\",
            r"\hline",
        ]
        for entry in systems:
            lines.append(
                f'{latex_escape(entry["system"])} & '
                f'{latex_escape(entry["class"])} & NOT RUN \\\\'
            )
        lines += [
            r"\hline",
            r"\end{tabular}",
            r"\end{table}",
        ]

        destination = Path(out_tex_path)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return str(destination)
